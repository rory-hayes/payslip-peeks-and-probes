const rows = tasks.map((task) => ({ ...base, ...task }));

function toCsvValue(value) {
  const text = value == null ? "" : String(value);
  return `"${text.replaceAll('"', '""')}"`;
}

function writeFallbackFiles() {
  const outDir = join(process.cwd(), "command-centre");
  mkdirSync(outDir, { recursive: true });

  const csv = [columns.join(","), ...rows.map((row) => columns.map((column) => toCsvValue(row[column])).join(","))].join("\n") + "\n";
  writeFileSync(join(outDir, `${PROJECT_SLUG}-roadmap.csv`), csv);
  writeFileSync(join(outDir, `${PROJECT_SLUG}-roadmap.json`), JSON.stringify(rows, null, 2) + "\n");
  writeFileSync(
    join(outDir, `${PROJECT_SLUG}-summary.json`),
    JSON.stringify(
      {
        project_name: PROJECT_NAME,
        project_slug: PROJECT_SLUG,
        repo_url: REPO_URL,
        deployment_url: DEPLOYMENT_URL,
        generated_at: GENERATED_AT,
        production_readiness_score: PRODUCTION_READINESS_SCORE,
        row_count: rows.length,
        priority_counts: rows.reduce((acc, row) => {
          acc[row.Priority] = (acc[row.Priority] ?? 0) + 1;
          return acc;
        }, {}),
        status_counts: rows.reduce((acc, row) => {
          acc[row.Status] = (acc[row.Status] ?? 0) + 1;
          return acc;
        }, {}),
        source: "Code Audit",
      },
      null,
      2,
    ) + "\n",
  );
}

async function postWebhook() {
  const url = process.env.COMMAND_CENTRE_WEBHOOK_URL;
  if (!url) return false;

  const res = await fetch(url, {
    method: "POST",
    headers: { "Content-Type": "application/json" },
    body: JSON.stringify({
      project_name: PROJECT_NAME,
      project_slug: PROJECT_SLUG,
      repo_url: REPO_URL,
      deployment_url: DEPLOYMENT_URL,
      generated_at: GENERATED_AT,
      production_readiness_score: PRODUCTION_READINESS_SCORE,
      rows,
    }),
  });

  if (!res.ok) {
    throw new Error(`Command centre webhook failed with HTTP ${res.status}`);
  }
  return true;
}

try {
  const posted = await postWebhook();
  if (posted) {
    console.log("Roadmap posted to command centre webhook.");
  } else {
    writeFallbackFiles();
    console.log("Command centre credentials not available; wrote local CSV/JSON exports.");
  }
} catch (error) {
  writeFallbackFiles();
  console.error(error instanceof Error ? error.message : String(error));
  console.error("Wrote local CSV/JSON exports instead.");
  process.exitCode = 1;
}
